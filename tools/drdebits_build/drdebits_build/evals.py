"""Evaluation harness for the behaviour tests.

The build exports the behaviour tests as ``evals/cases.json`` for a person to
run against a model by hand, and renders ``evals/RESULTS.md`` from the result
files a person records under ``evals/results/``. A result file carries the
model name, the run date, the guide version tested and one pass or fail per
case, and nothing else: no prompts, outputs or transcripts are ever committed.
Nothing here calls a model.
"""
from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path

from . import render
from .model import ModelError

CASES_FILE = "evals/cases.json"
RESULTS_FILE = "evals/RESULTS.md"
RESULTS_DIR = "evals/results"
VERDICTS = ("pass", "fail")
RESULT_KEYS = ("model", "run_date", "guide_version", "runner", "results")
# YYYY-MM-DD-<slug>.json, so results sort by date in a directory listing.
RESULT_NAME_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})-[a-z0-9]+(?:-[a-z0-9]+)*\.json$")

RESULTS_HEADER_TEMPLATE = (
    "# DrDebits evaluation results\n\n"
    "Part of [DrDebits](../drdebits.md) `{version}`. Generated by the build from "
    "`evals/results/*.json`; edit those files, never this table. Each run column is one "
    "manual evaluation: the model, the date and a pass or fail per behaviour test. No "
    "prompts, outputs or transcripts are recorded here or anywhere in this repository.\n\n"
)


def build_cases(s):
    """Export the behaviour tests as JSON for a manual run."""
    cases = [
        {
            "id": r["id"],
            "scenario": r["scenario"],
            "expected_status": r["expected_status"],
            "required_behaviour": r["required_behaviour"],
            "side_effect_check": r["side_effect_check"],
        }
        for r in s.behaviour
    ]
    payload = {"guide_version": s.meta["guide_version"], "cases": cases}
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def _load_result(path, rel, case_ids):
    match = RESULT_NAME_RE.match(path.name)
    if not match:
        raise ModelError(f"{rel}: file name must be YYYY-MM-DD-<slug>.json")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, UnicodeDecodeError) as exc:
        raise ModelError(f"{rel}: not valid JSON ({exc})") from exc
    if not isinstance(data, dict) or sorted(data) != sorted(RESULT_KEYS):
        raise ModelError(
            f"{rel}: keys must be exactly {', '.join(RESULT_KEYS)}; prompts, outputs and "
            "transcripts do not belong in a result file")
    for key in ("model", "run_date", "guide_version", "runner"):
        if not isinstance(data[key], str) or not data[key].strip():
            raise ModelError(f"{rel}: {key} must be a non-empty string")
    try:
        date.fromisoformat(data["run_date"])
    except ValueError as exc:
        raise ModelError(f"{rel}: run_date must be an ISO date (YYYY-MM-DD)") from exc
    if match.group(1) != data["run_date"]:
        raise ModelError(f"{rel}: file name date {match.group(1)} != run_date {data['run_date']}")
    results = data["results"]
    if not isinstance(results, dict):
        raise ModelError(f"{rel}: results must map each case id to pass or fail")
    missing = sorted(set(case_ids) - set(results))
    unexpected = sorted(set(results) - set(case_ids))
    if missing or unexpected:
        raise ModelError(
            f"{rel}: results must cover exactly the cases in {CASES_FILE}; "
            f"missing={missing}, unexpected={unexpected}")
    for case_id, verdict in results.items():
        if verdict not in VERDICTS:
            raise ModelError(f"{rel}: {case_id} must be pass or fail, got {verdict!r}")
    return data


def load_results(root, s):
    """Read and validate every recorded run, oldest first."""
    directory = Path(root) / RESULTS_DIR
    if not directory.is_dir():
        return []
    runs = []
    for path in sorted(directory.glob("*.json"), key=lambda p: p.name):
        runs.append(_load_result(path, f"{RESULTS_DIR}/{path.name}", [r["id"] for r in s.behaviour]))
    return runs


def build_results_md(root, s):
    """Render the results table: one row per case, one column per run."""
    runs = load_results(root, s)
    headers = ["ID", "Expected status"] + [f"{r['model']} ({r['run_date']})" for r in runs]
    rows = [[c["id"], c["expected_status"]] + [r["results"][c["id"]] for r in runs]
            for c in s.behaviour]
    total = len(s.behaviour)
    rows.append(["Passed", f"of {total}"]
                + [str(sum(v == "pass" for v in r["results"].values())) for r in runs])
    body = render.render_table(headers, ["---"] * len(headers), rows)
    if not runs:
        body = f"No runs recorded yet. Add a file under `{RESULTS_DIR}/` and rebuild.\n\n" + body
    return RESULTS_HEADER_TEMPLATE.format(version=s.meta["guide_version"]) + body
